// Dot-grid map of the contiguous United States, Albers equal-area conic projection.
const D = Math.PI / 180;
const P1 = 29.5 * D, P2 = 45.5 * D, P0 = 37.5 * D, L0 = -96 * D;
const N = (Math.sin(P1) + Math.sin(P2)) / 2;
const C = Math.cos(P1) ** 2 + 2 * N * Math.sin(P1);
const R0 = Math.sqrt(C - 2 * N * Math.sin(P0)) / N;

function raw(lng: number, lat: number): [number, number] {
  const r = Math.sqrt(C - 2 * N * Math.sin(lat * D)) / N;
  const t = N * (lng * D - L0);
  return [r * Math.sin(t), -(R0 - r * Math.cos(t))];
}

