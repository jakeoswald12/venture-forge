const PAD = 14;
export const MAP_W = 1000;

const rawOutline = OUTLINE.map(([a, b]) => raw(a, b));
const xs = rawOutline.map((p) => p[0]);
const ys = rawOutline.map((p) => p[1]);
const minX = Math.min(...xs), maxX = Math.max(...xs), minY = Math.min(...ys), maxY = Math.max(...ys);
const S = (MAP_W - PAD * 2) / (maxX - minX);
export const MAP_H = Math.round((maxY - minY) * S + PAD * 2);

export function project(lng: number, lat: number): Pt {
  const [x, y] = raw(lng, lat);
  return [(x - minX) * S + PAD, (y - minY) * S + PAD];
}

function inside(poly: Pt[], x: number, y: number) {
  let c = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i];
    const [xj, yj] = poly[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) c = !c;
  }
  return c;
}

const outline = OUTLINE.map(([a, b]) => project(a, b));
const lake = LAKE.map(([a, b]) => project(a, b));

function build(step: number) {
  const rowH = step * 0.866;
  let d = "";
  let row = 0;
  for (let y = PAD; y <= MAP_H - PAD; y += rowH, row++) {
    for (let x = PAD + (row % 2 ? step / 2 : 0); x <= MAP_W - PAD; x += step) {
      if (inside(outline, x, y) && !inside(lake, x, y)) d += `M${x.toFixed(1)} ${y.toFixed(1)}h0`;
    }
  }
  return d;
}

export const DOTS = build(13);
